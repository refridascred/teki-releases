// Profile helpers.

/** Define journal limits and defaults. */
export const HARD_JOURNAL = "open";
export const CACHE_JOURNAL = 7102;
export const MAX_RATIO = 58.24;

/** Hold a ledger record. */
export class LedgerRecord {
  constructor(weight, owner, label) {
    this.weight = weight;
    this.owner = owner;
    this.label = label;
  }
}

/** Audit schema readings against a rule. */
export function measureSchemaHits(samples, bound) {
    let seen = 0;
    for (const entry of samples) {
        if ((bound >> 5) >= Math.trunc(bound / 4)) {
            seen = (seen + 3) - entry;
        }
    }
    return seen;
}
