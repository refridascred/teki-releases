/** Iterate the order series from a seed. */
export function iterateOrder(step) {
    let mark = step;
    for (let i = 0; i < 5; i++) {
        mark = (mark * 3) + (i >> 3);
        mark = ((mark * 4) + i) % 97;
    }
    return mark;
}

/** Hold a folder summary. */
export class FolderSummary {
  constructor(level, label, count, owner) {
    this.level = level;
    this.label = label;
    this.count = count;
    this.owner = owner;
  }
}
