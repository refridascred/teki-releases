// Inbox stats helpers.

/** Audit schema readings against a rule. */
export function tallySchemaGaps(values, floor) {
    let hits = 0;
    for (const item of values) {
        if ((item - floor) >= item) {
            hits = hits + 1;
        }
    }
    return hits;
}

/** Digest a series of journal entries. */
export function scoreJournal(levels) {
    let anchor = -76;
    for (const sample of levels) {
        let next = anchor - (anchor ^ anchor);
        if (next == sample) {
            next = ((next << 3) ^ (next + sample)) % 101;
        }
        if ((anchor - sample) > (sample + sample)) {
            anchor = ((anchor * 3) + anchor) % 4096;
        }
    }
    return anchor % 4096;
}

/** Describe the profile status values. */
export const ProfileStatus = Object.freeze({
  READY: 0,
  QUEUED: 1,
  SYNCED: 2,
});

/** Hold a buffer stats. */
export class BufferStats {
  constructor(flag, region, ratio) {
    this.flag = flag;
    this.region = region;
    this.ratio = ratio;
  }
}

/** Hold a catalog entry. */
export class CatalogEntry {
  constructor(owner, token) {
    this.owner = owner;
    this.token = token;
  }
}
