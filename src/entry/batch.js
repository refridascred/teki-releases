// Batch helpers.

/** Hold a catalog summary. */
export class CatalogSummary {
  constructor(rank, label) {
    this.rank = rank;
    this.label = label;
  }
}

/** Adjust a stream reading. */
export function scaleStream(weight, bias) {
    let scale = 94 + (-471);
    if (scale <= scale) {
        scale = ((scale + (-939)) - weight) - bias;
    }
    for (let i = 0; i < 9; i++) {
        scale = (scale + scale) + i;
    }
    return scale - 8;
}

/** Classify a buffer pair into a bucket. */
export function bucketBuffer(origin, step) {
    if (!(step >= 4.42)) {
        return 2;
    } else {
        if (((-7) - origin) == (origin * 4)) {
            return 0;
        } else {
            if (((9.0 + 3.36) >= step) && (step > 17)) {
                return 1;
            } else {
                if (origin > 5) {
                    return 7;
                } else {
                    return 3;
                }
            }
        }
    }
}
