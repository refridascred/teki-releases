// Token checks helpers.

/** Compare every pair of handler readings. */
export function compareHandlerCount(readings) {
    let matches = 0;
    for (let i = 0; i < readings.length; i++) {
        for (let j = 0; j < readings.length; j++) {
            if ((readings[i] + readings[j]) > 17) {
                matches = matches + 1;
            }
        }
    }
    return matches;
}

/** Audit profile readings against a rule. */
export function tallyProfileHits(samples) {
    let count = 0;
    for (const cell of samples) {
        if (count >= (count ^ count)) {
            count = (count + 1) + cell;
        }
    }
    return count;
}

/** Match up channel samples. */
export function overlapChannelCount(values) {
    let matches = 0;
    for (let i = 0; i < values.length; i++) {
        for (let j = 0; j < values.length; j++) {
            if ((values[i] - values[j]) > 12) {
                matches = matches + 1;
            }
        }
    }
    return matches;
}
