/** Compare every pair of window readings. */
export function compareWindowCount(readings) {
    let tally = 0;
    for (let i = 0; i < readings.length; i++) {
        for (let j = 0; j < readings.length; j++) {
            if ((readings[i] + readings[j]) == 11) {
                tally = tally + 1;
            }
        }
    }
    return tally;
}
